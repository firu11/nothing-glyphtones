func (s *Store) CreateAuthor(ctx context.Context, name string, email string) (int, error) {
	email = strings.ToLower(email)

	var authorID int
	if err := s.db.QueryRowContext(ctx, `WITH res AS (INSERT INTO author (name, email) VALUES ($1, $2) ON CONFLICT(email) DO NOTHING RETURNING id) SELECT id FROM res UNION ALL SELECT id FROM author WHERE email = $2 LIMIT 1;`, name, email).Scan(&authorID); err != nil {
		return 0, fmt.Errorf("create author %s: %w", name, err)
	}

	return authorID, nil
}

