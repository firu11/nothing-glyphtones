func (s *Store) Vote(ctx context.Context, userID int, displayID string, vote int) error {
	var err error
	if vote == 0 {
		_, err = s.db.ExecContext(ctx, `DELETE FROM vote WHERE author_id = $1 AND ringtone_id = (SELECT id FROM ringtone WHERE display_id = $2)`, userID, displayID)
	} else {
		_, err = s.db.ExecContext(ctx, `INSERT INTO vote (author_id, ringtone_id, up) SELECT $1, r.id, $3 FROM ringtone r WHERE r.display_id = $2 AND r.author_id != $1 ON CONFLICT (author_id, ringtone_id) DO UPDATE SET up = EXCLUDED.up;`, userID, displayID, vote == 1)
	}
	if err != nil {
		return fmt.Errorf("vote for ringtone %s: %w", displayID, err)
	}
	return nil
}

func calcPages(ringtones []RingtoneModel) int {
	if len(ringtones) == 0 {
		return 0
	}
	return int(math.Ceil(float64(ringtones[0].NumberOfResults) / float64(resultsPerPage)))
}
