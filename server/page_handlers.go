func (s *Server) index(c *echo.Context) error {
	if c.QueryParams().Has("reset-filters") {
		setLastSearchCookie(c, "/", -1)
		return c.Redirect(http.StatusTemporaryRedirect, "/")
	}
	if len(c.QueryParams()) == 0 {
		cookie, err := c.Cookie(lastSearchCookieName)
		if err == nil && cookie.Value != "/" {
			return c.Redirect(http.StatusTemporaryRedirect, cookie.Value)
		} else {
			setLastSearchCookie(c, c.Request().RequestURI, 1_000_000)
		}
	} else {
		setLastSearchCookie(c, c.Request().RequestURI, 1_000_000)
	}

	filters := parseSearchFilters(c)
	authorID := s.currentUserID(c)
	ctx := c.Request().Context()

	ringtones, numberOfPages, err := s.store.GetRingtones(ctx, filters.Search, filters.Category, filters.SortBy, filters.Phones, filters.Effects, filters.AutoGenerated, filters.Page, authorID)
	if err != nil {
		return internalError(c, "query ringtones", err, !isHX(c))
	}

	effects, err := s.store.GetEffects(ctx)
	if err != nil {
		return internalError(c, "query effects", err, !isHX(c))
	}

	if isHX(c) {
		return Render(c, components.ListOfRingtones(ringtones, effects, numberOfPages, filters.Page, authorID, "", "index"))
	}

	phones, err := s.store.GetPhones(ctx)
	if err != nil {
		return internalError(c, "query phones", err, true)
	}
	for i := range phones {
		phones[i].Selected = slices.Contains(filters.Phones, phones[i].ID)
	}
	for i := range effects {
		effects[i].Selected = slices.Contains(filters.Effects, effects[i].ID)
	}

	data := views.IndexData{
		Ringtones:        ringtones,
		Phones:           phones,
		Effects:          effects,
		Category:         filters.Category,
		SortBy:           filters.SortBy,
		SearchQuery:      filters.Search,
		AutoGenerated:    filters.AutoGenerated,
		NumberOfPages:    numberOfPages,
		Page:             filters.Page,
		LoggedInAuthorID: authorID,
	}
	return Render(c, views.Index(data))
}

func (s *Server) author(c *echo.Context) error {
	authorName := c.Param("name")
	if authorName == "" {
		return c.Redirect(http.StatusTemporaryRedirect, "/")
	}

	pageNumber := parseIntOrDefault(c.QueryParam("page"), 1)
	userID := s.currentUserID(c)
	ctx := c.Request().Context()

	ringtones, numberOfPages, err := s.store.GetRingtonesByAuthor(ctx, authorName, pageNumber, userID)
	if err != nil {
		return internalError(c, "query author ringtones", err, !isHX(c))
	}

	var effects []database.EffectModel
	if userID == 1 {
		effects, err = s.store.GetEffects(ctx)
		if err != nil {
			return internalError(c, "query effects", err, !isHX(c))
		}
	}

	if isHX(c) {
		return Render(c, components.ListOfRingtones(ringtones, effects, numberOfPages, pageNumber, userID, authorName, "profile"))
	}

	author, err := s.store.GetAuthorByName(ctx, authorName)
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return Render(c, views.NotFoundView(userID != 0))
		}
		return internalError(c, "get author", err, true)
	}

	data := views.ProfileData{
		Ringtones:        ringtones,
		Effects:          effects,
		NumberOfPages:    numberOfPages,
		Page:             pageNumber,
		Author:           author,
		LoggedInAuthorId: userID,
	}
	return Render(c, views.Profile(data))
}

func (s *Server) me(c *echo.Context) error {
	userID := s.currentUserID(c)
	if userID == 0 {
		return c.Redirect(http.StatusTemporaryRedirect, "/")
	}

	user, err := s.store.GetAuthor(c.Request().Context(), userID)
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			s.auth.RemoveAuthCookie(c)
		}
		return internalError(c, "get current author", err, true)
	}

	return c.Redirect(http.StatusPermanentRedirect, fmt.Sprintf("/author/%s", user.Name))
}

