func (s *Server) authorRenameView(c *echo.Context) error {
	authorID := s.currentUserID(c)
	if authorID == 0 {
		return Render(c, views.OtherErrorView(http.StatusBadRequest, errors.New("You're not logged in.")))
	}
	author, err := s.store.GetAuthor(c.Request().Context(), authorID)
	if err != nil {
		return internalError(c, "get author for rename", err, true)
	}

	return Render(c, components.EditName(author.Name, nil))
}

func (s *Server) authorRename(c *echo.Context) error {
	authorID := s.currentUserID(c)
	if authorID == 0 {
		return errors.New("You're not logged in.")
	}
	newName := strings.ToLower(strings.TrimSpace(c.FormValue("name")))
	if !authorNameR.MatchString(newName) {
		return Render(
			c, components.EditName(
				newName,
				errors.New("Invalid name. Maximal length is 20 letters. Only letters, numbers and '_-' are allowed."),
			),
		)
	}
	if err := s.store.RenameAuthor(c.Request().Context(), authorID, newName); err != nil {
		return internalError(c, "rename author", err, false)
	}

	c.Response().Header().Add("HX-Redirect", "/me")

	return c.NoContent(http.StatusOK)
}
